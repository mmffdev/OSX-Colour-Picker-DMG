// Reads every Markdown file under `base` (relative to the Astro project root) as a Starlight page.
// The page title is the file's first "# " heading, which is removed from the body; no frontmatter is needed,
// so the files stay exactly what the app's Help menu renders. Folders in `exclude` are skipped.
import { readdir, readFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export function helpLoader({ base, exclude = [] }) {
  return {
    name: 'colorgain-help',
    async load({ store, parseData, renderMarkdown, logger, watcher, config }) {
      const root = path.resolve(fileURLToPath(config.root), base);
      watcher?.add(root);
      const files = await walk(root, exclude);
      store.clear();

      // The home page: a splash that points at the first guide.
      store.set({
        id: 'index',
        data: await parseData({
          id: 'index',
          data: {
            title: 'Help',
            template: 'splash',
            hero: {
              title: 'Colorgain',
              tagline: 'Colour management and proofing for 2D, 3D, video, design and print.',
              actions: [{ text: 'Getting started', link: '/getting-started/', icon: 'right-arrow' }],
            },
          },
        }),
        body: '',
        filePath: 'src/content/docs/index.md',
        rendered: { html: '' },
      });

      for (const file of files) {
        const text = await readFile(file, 'utf8');
        const rel = path.relative(root, file).replace(/\\/g, '/');
        const id = rel.replace(/\.md$/i, '').toLowerCase().replace(/[^a-z0-9/]+/g, '-');
        const match = text.match(/^#\s+(.+?)\s*$/m);
        const title = match ? match[1] : path.basename(file, '.md');
        const body = match ? text.replace(match[0], '').trimStart() : text;
        const data = await parseData({ id, data: { title } });
        // Starlight places sidebar entries by a path under src/content/docs, so each page gets a virtual one in help/ (the autogenerated group in astro.config.mjs).
        store.set({ id, data, body, filePath: `src/content/docs/help/${id}.md`, rendered: await renderMarkdown(body) });
      }
      logger.info(`${files.length} help page(s) from ${path.relative(fileURLToPath(config.root), root)}`);
    },
  };
}

async function walk(dir, exclude) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!exclude.includes(entry.name)) out.push(...(await walk(path.join(dir, entry.name), exclude)));
    } else if (/\.md$/i.test(entry.name)) {
      out.push(path.join(dir, entry.name));
    }
  }
  return out.sort();
}
